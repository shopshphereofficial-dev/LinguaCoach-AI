/// A lesson together with its position on the path.
class LessonSlot {
  final Unit unit;
  final LessonNode lesson;
  final int unitIndex;
  final int lessonIndex;
  final int flatIndex;

  const LessonSlot({
    required this.unit,
    required this.lesson,
    required this.unitIndex,
    required this.lessonIndex,
    required this.flatIndex,
  });
}

/// Every lesson on the path, in order.
final List<LessonSlot> kLessonPath = () {
  final slots = <LessonSlot>[];
  var flat = 0;
  for (var u = 0; u < kCurriculum.length; u++) {
    final unit = kCurriculum[u];
    for (var l = 0; l < unit.lessons.length; l++) {
      slots.add(LessonSlot(
        unit: unit,
        lesson: unit.lessons[l],
        unitIndex: u,
        lessonIndex: l,
        flatIndex: flat,
      ));
      flat++;
    }
  }
  return slots;
}();

/// A generated, cacheable lesson pack.
class LessonContent {
  final String title;
  final List<VocabItem> vocabulary;
  final List<SentencePair> sentences;
  final List<QuizQuestion> quiz;
  final String speakingTask;
  final String speakingHint;

  const LessonContent({
    required this.title,
    required this.vocabulary,
    required this.sentences,
    required this.quiz,
    required this.speakingTask,
    required this.speakingHint,
  });

  Map<String, dynamic> toJson() => {
        'title': title,
        'vocabulary': [
          for (final v in vocabulary)
            {'term': v.term, 'translation': v.translation, 'example': v.example}
        ],
        'sentences': [
          for (final s in sentences) {'target': s.target, 'native': s.native}
        ],
        'quiz': [
          for (final q in quiz)
            {
              'type': q.type,
              'prompt': q.prompt,
              'options': q.options,
              'answer': q.answer,
              'explanation': q.explanation,
            }
        ],
        'speakingTask': speakingTask,
        'speakingHint': speakingHint,
      };

  factory LessonContent.fromJson(Map<String, dynamic> json) {
    final vocab = <VocabItem>[];
    if (json['vocabulary'] is List) {
      for (final v in json['vocabulary'] as List) {
        if (v is Map) vocab.add(VocabItem.fromJson(Map<String, dynamic>.from(v)));
      }
    }
    final sentences = <SentencePair>[];
    if (json['sentences'] is List) {
      for (final s in json['sentences'] as List) {
        if (s is Map) {
          sentences.add(SentencePair.fromJson(Map<String, dynamic>.from(s)));
        }
      }
    }
    final quiz = <QuizQuestion>[];
    if (json['quiz'] is List) {
      for (final q in json['quiz'] as List) {
        if (q is Map) {
          quiz.add(QuizQuestion.fromJson(Map<String, dynamic>.from(q)));
        }
      }
    }
    return LessonContent(
      title: (json['title'] ?? 'Lesson').toString(),
      vocabulary: vocab,
      sentences: sentences,
      quiz: quiz,
      speakingTask: (json['speakingTask'] ?? '').toString(),
      speakingHint: (json['speakingHint'] ?? '').toString(),
    );
  }
}
