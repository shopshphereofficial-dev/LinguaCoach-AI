/// One lesson on the learning path.
class LessonNode {
  /// Stable id, e.g. 'u1l2'. Used as the cache key for generated content.
  final String id;
  final String title;
  final String emoji;

  /// The topic handed to Gemini when generating this lesson's content.
  final String topic;

  const LessonNode({
    required this.id,
    required this.title,
    required this.emoji,
    required this.topic,
  });
}

/// A unit groups lessons of the same level and theme.
class Unit {
  final String id;
  final String title;
  final String subtitle;
  final SkillLevel level;
  final Color color;
  final List<LessonNode> lessons;

  const Unit({
    required this.id,
    required this.title,
    required this.subtitle,
    required this.level,
    required this.color,
    required this.lessons,
  });
}

